"""The repo lane: read a checkout, then write one inert ticket into it.

A repo is never a netwatch target. What a checkout gets is a file: what is wrong with its
dependency state and what to do about it. The file is safe to commit or delete, it never
runs anything, and it is never staged.

Every git call lives in `git()` so the side-effect flags are in exactly one place: reading
a foreign checkout must not refresh its index, start its filesystem monitor, or invoke a
configured signature program.
"""
import json
import os
import secrets
import stat
import subprocess
import time
import tomllib
from pathlib import Path

from . import sources
from .core import Error

HEADER = "# netwatch findings — generated by netwatch"
TICKET = ".netwatch"
TEMP_PREFIX = ".netwatch.tmp-"
TEMP_AGE = 3600
STALE_DAYS = 90
GIT_ENV = {"GIT_OPTIONAL_LOCKS": "0"}
GIT_CONFIG = ("-c", "core.fsmonitor=", "-c", "core.untrackedCache=")
GIT_NO_SIGN = ("-c", "log.showSignature=false")

MANIFEST_LOCK = (
    ("pyproject.toml", "uv.lock", "uv", "uv lock"),
    ("package.json", "package-lock.json", "npm", "npm install --package-lock-only"),
)


class Refused(Error):
    """The ticket was not written; `str()` says why, and nothing was touched."""


def git(repo, *args, runner=subprocess.run):
    # --no-optional-locks is a top-level option, so it precedes the subcommand; the
    # signature override must precede the subcommand too, while --no-show-signature is a
    # `git log` option and belongs after it.
    argv = ["git", "--no-optional-locks", "-C", str(repo), *GIT_CONFIG]
    if args and args[0] == "log":
        argv.extend(GIT_NO_SIGN)
        argv.extend(["log", "--no-show-signature", *args[1:]])
    else:
        argv.extend(args)
    if runner is subprocess.run:
        result = subprocess.run(argv, capture_output=True, text=True, env={**os.environ, **GIT_ENV})
        if result.returncode != 0:
            raise Error("git failed: " + (result.stderr or "").strip()[:200])
        return result.stdout
    return runner(argv, env={**os.environ, **GIT_ENV})


def _tracked(repo, name, runner):
    try:
        git(repo, "ls-files", "--error-unmatch", name, runner=runner)
        return True
    except Error:
        return False


def _modified(repo, name, runner):
    out = git(repo, "status", "--porcelain", "--", name, runner=runner)
    return bool(str(out).strip())


def _last_touch(repo, name, runner):
    out = git(repo, "log", "-1", "--format=%ct", "--", name, runner=runner)
    try:
        return int(str(out).strip())
    except ValueError:
        return None


def _uv_lock_packages(path):
    data = tomllib.loads(path.read_text())
    packages = []
    for row in data.get("package", []):
        if isinstance(row, dict) and "name" in row and "version" in row:
            packages.append({"name": row["name"], "version": row["version"], "ecosystem": "PyPI"})
    return packages


def _npm_lock_packages(path):
    data = json.loads(path.read_text())
    packages = []
    for key, row in (data.get("packages") or {}).items():
        if not key or not isinstance(row, dict) or "version" not in row:
            continue
        name = row.get("name") or key.rsplit("node_modules/", 1)[-1]
        packages.append({"name": name, "version": row["version"], "ecosystem": "npm",
                         "direct": key.count("node_modules/") == 1})
    return packages


def _advisories(packages, request, incomplete):
    findings = []
    for package in packages:
        body = {"package": {"name": package["name"], "ecosystem": package["ecosystem"]},
                "version": package["version"]}
        try:
            data = request(sources.OSV, body)
        except Error as exc:
            incomplete.append("%s advisory query failed: %s" % (package["name"], exc))
            continue
        queried = {"ecosystem": package["ecosystem"], "name": package["name"],
                   "version": package["version"]}
        try:
            matched = sources.osv(queried, data)
        except Error as exc:
            incomplete.append("%s advisory response unusable: %s" % (package["name"], exc))
            continue
        for item in matched:
            findings.append({
                "type": "advisory",
                "severity": "high",
                "ecosystem": package["ecosystem"],
                "advisory": item.get("advisory"),
                "package": package["name"],
                "version": package["version"],
                "fixed": item.get("fix_versions") or [],
                "source": package.get("source"),
                "direct": package.get("direct", True),
                "action_kind": "edit-config",
                "action": _advice(package, item.get("fix_versions") or []),
            })
    return findings


def _advice(package, fixed):
    if not fixed:
        return "no fixed version is published yet; track the advisory and plan a replacement"
    target = fixed[-1]
    if package["ecosystem"] == "npm":
        return ("add an npm override for %s@%s to package.json, run npm install, verify the "
                "resolved version in package-lock.json, then commit lockfile and manifest together"
                % (package["name"], target))
    return ("raise the %s requirement to >=%s in pyproject.toml, run uv lock, then commit "
            "lockfile and manifest together" % (package["name"], target))


def collect(repo, *, request=sources.fetch, runner=subprocess.run):
    """Findings plus leads for one checkout. Never writes anything."""
    repo = Path(repo) if not isinstance(repo, Path) else repo
    findings, leads, incomplete = [], [], []
    for manifest, lock, ecosystem, action in MANIFEST_LOCK:
        if not (repo / manifest).is_file():
            continue
        if not (repo / lock).is_file():
            findings.append({"type": "unpinned", "severity": "high", "ecosystem": ecosystem,
                             "evidence": "%s present, %s absent" % (manifest, lock),
                             "action_kind": "command",
                             "action": "%s && git add %s && git commit %s" % (action, lock, lock)})
            continue
        if not _tracked(repo, lock, runner):
            findings.append({"type": "not_revertible", "severity": "high", "ecosystem": ecosystem,
                             "evidence": "%s is not committed" % lock,
                             "action_kind": "command",
                             "action": "git add %s && git commit %s" % (lock, lock)})
        elif _modified(repo, lock, runner):
            findings.append({"type": "drifted", "severity": "medium", "ecosystem": ecosystem,
                             "evidence": "%s differs from the committed state" % lock,
                             "action_kind": "manual",
                             "action": "review the change and commit it, or restore the committed %s" % lock})
        touched = _last_touch(repo, lock, runner)
        if touched is not None and time.time() - touched > STALE_DAYS * 86400:
            leads.append({"type": "staleness",
                          "detail": "%s was last touched %d days ago" % (lock, (time.time() - touched) // 86400)})
        try:
            packages = (_uv_lock_packages(repo / lock) if lock == "uv.lock"
                        else _npm_lock_packages(repo / lock))
        except (ValueError, OSError, tomllib.TOMLDecodeError) as exc:
            incomplete.append("%s unreadable: %s" % (lock, type(exc).__name__))
            continue
        for package in packages:
            package["source"] = lock
        findings.extend(_advisories(packages, request, incomplete))

    payload = {"netwatch": 1,
               "generated": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
               "collection": "incomplete" if incomplete else "complete",
               "findings": findings,
               "leads": leads}
    if incomplete:
        payload["error"] = "; ".join(incomplete)
    return payload, incomplete


def render(payload):
    """Human-legible top, machine-consumable bottom, one header line."""
    lines = [HEADER + " " + payload.get("version", "0.2.0") + " at " + payload["generated"],
             "This file is a ticket from netwatch. It is safe to commit or to delete;",
             "netwatch re-writes it on each scan of the workspace that owns this checkout."]
    if payload.get("collection") != "complete":
        lines.extend(["", "Collection was **incomplete**: " + payload.get("error", "unknown reason")])
    lines.extend(["", "Findings:"])
    if not payload["findings"]:
        lines.append("- none")
    for finding in payload["findings"]:
        if finding["type"] == "advisory":
            lines.append("- advisory: `%s %s` (%s, %s) is affected by %s%s; %s" % (
                finding["package"], finding["version"], finding["source"], finding["ecosystem"],
                finding["advisory"],
                ", fixed in " + ", ".join(finding["fixed"]) if finding["fixed"] else "",
                finding["action"]))
        else:
            lines.append("- %s: %s — %s" % (finding["type"], finding["evidence"], finding["action"]))
    if payload["leads"]:
        lines.extend(["", "Leads (not findings — no advisory claim):"])
        for lead in payload["leads"]:
            lines.append("- %s: %s" % (lead["type"], lead["detail"]))
    lines.extend(["", "```json", json.dumps(payload, indent=1, sort_keys=True), "```"])
    return "\n".join(lines) + "\n"


def should_write(payload, repo):
    """Rule 3: a scan that collected nothing never overwrites, and never invents a ticket.

    A partially collected scan does write: the ticket names what failed, so it reads as
    incomplete rather than as a clean check. Only a run that collected nothing at all is
    silent — leaving a previous ticket untouched, and creating none where none existed.
    """
    del repo
    return payload.get("collection") == "complete" or bool(payload.get("findings")) \
        or bool(payload.get("leads"))


def _clean_temps(repo):
    cutoff = time.time() - TEMP_AGE
    for entry in repo.iterdir():
        name = entry.name
        if not name.startswith(TEMP_PREFIX):
            continue
        suffix = name[len(TEMP_PREFIX):]
        if len(suffix) != 32 or any(c not in "0123456789abcdef" for c in suffix):
            continue
        try:
            if entry.stat().st_mtime < cutoff:
                entry.unlink()
        except OSError:
            continue


def write(repo, text):
    """Publish a ticket: temp file, pre-rename re-verification, rename.

    The temp name carries 32 random hex characters so a half-written file is
    recognizable as ours by name alone — its content may be truncated by the very crash
    the temp exists to survive.
    """
    repo = Path(repo)
    target = repo / TICKET
    if target.exists() or target.is_symlink():
        try:
            status = target.lstat()
        except OSError as exc:
            raise Refused("could not inspect %s: %s" % (TICKET, exc))
        if not stat.S_ISREG(status.st_mode):
            raise Refused("%s is not a regular file; nothing was followed or written" % TICKET)
        try:
            first = target.read_text(errors="replace").splitlines()[:1]
        except OSError as exc:
            raise Refused("could not read %s: %s" % (TICKET, exc))
        if not first or not first[0].startswith(HEADER):
            raise Refused("%s was written by something else; left alone" % TICKET)
    _clean_temps(repo)
    temp = repo / (TEMP_PREFIX + secrets.token_hex(16))
    fd = os.open(temp, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
    try:
        with os.fdopen(fd, "w") as handle:
            handle.write(text)
        # Re-verify immediately before the rename: between the check above and here,
        # another writer may have published, or a foreign file may have appeared.
        if target.exists() and not target.is_symlink():
            try:
                first = target.read_text(errors="replace").splitlines()[:1]
            except OSError:
                first = []
            if not first or not first[0].startswith(HEADER):
                raise Refused("%s changed to a foreign file; left alone" % TICKET)
        os.replace(temp, target)
    except BaseException:
        try:
            temp.unlink()
        except OSError:
            pass
        raise
    return "written"


def exists(repo):
    return (Path(repo) / TICKET).is_file()
