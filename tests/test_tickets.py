import json
import os
import shutil
import subprocess
import tempfile
import time
import unittest
from pathlib import Path

from netwatch import sources, tickets

HEADER = "# netwatch findings — generated by netwatch"


def git(repo, *args):
    subprocess.run(["git", "-C", str(repo), "-c", "user.email=a@b", "-c", "user.name=a", *args],
                   check=True, capture_output=True)


class RepoCase(unittest.TestCase):
    def setUp(self):
        self.root = Path(tempfile.mkdtemp())
        self.repo = self.root / "r"
        self.repo.mkdir()
        git(self.repo, "init", "-q")

    def tearDown(self):
        shutil.rmtree(self.root, ignore_errors=True)

    def commit_all(self, message="x"):
        git(self.repo, "add", "-A")
        git(self.repo, "commit", "-qm", message)

    def no_network(self, url, body=None):
        return {"vulns": []}


class FindingTests(RepoCase):
    def test_manifest_without_lockfile_is_unpinned(self):
        (self.repo / "pyproject.toml").write_text("[project]\nname='x'\n")
        self.commit_all()
        payload, incomplete = tickets.collect(self.repo, request=self.no_network)
        self.assertEqual([f["type"] for f in payload["findings"]], ["unpinned"])
        self.assertIn("uv lock", payload["findings"][0]["action"])
        self.assertEqual(incomplete, [])

    def test_lockfile_present_but_untracked_is_not_revertible(self):
        (self.repo / "pyproject.toml").write_text("[project]\nname='x'\n")
        (self.repo / "uv.lock").write_text("")
        self.commit_all()
        (self.repo / "package.json").write_text('{"name":"x"}')
        (self.repo / "package-lock.json").write_text(json.dumps(
            {"lockfileVersion": 3, "packages": {"": {}}}))
        payload, _ = tickets.collect(self.repo, request=self.no_network)
        types = [f["type"] for f in payload["findings"]]
        self.assertIn("not_revertible", types)

    def test_modified_lockfile_is_drifted(self):
        (self.repo / "pyproject.toml").write_text("[project]\nname='x'\n")
        (self.repo / "uv.lock").write_text("")
        self.commit_all()
        (self.repo / "uv.lock").write_text("changed")
        payload, _ = tickets.collect(self.repo, request=self.no_network)
        self.assertIn("drifted", [f["type"] for f in payload["findings"]])

    def test_advisory_comes_from_the_resolved_versions(self):
        (self.repo / "package.json").write_text('{"name":"x"}')
        (self.repo / "package-lock.json").write_text(json.dumps({
            "lockfileVersion": 3,
            "packages": {"": {}, "node_modules/minimist": {"version": "1.2.0"}},
        }))
        self.commit_all()

        def request(url, body=None):
            return {"vulns": [{"id": "GHSA-example", "affected": [{
                "package": {"ecosystem": "npm", "name": "minimist"},
                "ranges": [{"events": [{"introduced": "0"}, {"fixed": "1.2.3"}]}],
            }]}]}

        payload, _ = tickets.collect(self.repo, request=request)
        advisory = [f for f in payload["findings"] if f["type"] == "advisory"][0]
        self.assertEqual(advisory["advisory"], "GHSA-example")
        self.assertEqual(advisory["package"], "minimist")
        self.assertEqual(advisory["version"], "1.2.0")
        self.assertEqual(advisory["fixed"], ["1.2.3"])
        self.assertEqual(advisory["source"], "package-lock.json")

    def test_unparseable_lockfile_marks_collection_incomplete(self):
        (self.repo / "pyproject.toml").write_text("[project]\nname='x'\n")
        (self.repo / "uv.lock").write_text("this is not toml = = =")
        self.commit_all()
        payload, incomplete = tickets.collect(self.repo, request=self.no_network)
        self.assertEqual(payload["collection"], "incomplete")
        self.assertTrue(incomplete)

    def test_staleness_is_a_lead_not_a_finding(self):
        (self.repo / "pyproject.toml").write_text("[project]\nname='x'\n")
        (self.repo / "uv.lock").write_text("")
        old = int(time.time()) - 60 * 60 * 24 * 240
        git(self.repo, "add", "-A")
        env = {**os.environ,
               "GIT_AUTHOR_DATE": "@%d +0000" % old,
               "GIT_COMMITTER_DATE": "@%d +0000" % old}
        subprocess.run(["git", "-C", str(self.repo), "-c", "user.email=a@b", "-c", "user.name=a",
                        "commit", "-qm", "old"], check=True, capture_output=True, env=env)
        payload, _ = tickets.collect(self.repo, request=self.no_network)
        self.assertEqual([l["type"] for l in payload["leads"]], ["staleness"])
        self.assertNotIn("staleness", [f["type"] for f in payload["findings"]])


class ScreenTests(RepoCase):
    """A screen answers for every package at once; detail runs only where it flags."""

    def setUp(self):
        super().setUp()
        (self.repo / "package.json").write_text('{"name":"x"}')
        (self.repo / "package-lock.json").write_text(json.dumps({
            "lockfileVersion": 3,
            "packages": {"": {},
                         "node_modules/minimist": {"version": "1.2.0"},
                         "node_modules/lodash": {"version": "4.17.20"},
                         "node_modules/chalk": {"version": "5.0.0"}},
        }))
        self.commit_all()

    def test_a_clean_tree_issues_no_detail_requests(self):
        # manifest + lockfile with three packages, screen says none are affected
        screened, details = [], []
        def screen(queries):
            screened.append(len(queries)); return [[] for _ in queries]
        def request(url, body=None):
            details.append(url); return {"vulns": []}
        payload, incomplete = tickets.collect(self.repo, request=request, screen=screen)
        self.assertEqual(screened, [3])
        self.assertEqual(details, [])

    def test_a_flagged_package_still_produces_the_same_finding(self):
        def screen(queries): return [["GHSA-x"] if q["package"]["name"] == "minimist" else []
                                     for q in queries]
        def request(url, body=None):
            return {"vulns": [{"id": "GHSA-x", "affected": [{
                "package": {"ecosystem": "npm", "name": "minimist"},
                "ranges": [{"events": [{"introduced": "0"}, {"fixed": "1.2.3"}]}]}]}]}
        payload, _ = tickets.collect(self.repo, request=request, screen=screen)
        advisory = [f for f in payload["findings"] if f["type"] == "advisory"][0]
        self.assertEqual(advisory["advisory"], "GHSA-x")
        self.assertEqual(advisory["fixed"], ["1.2.3"])

    def test_a_failed_screen_marks_the_advisory_check_incomplete(self):
        def screen(queries): raise sources.Error("batch refused")
        payload, incomplete = tickets.collect(self.repo, request=lambda u, b=None: {"vulns": []},
                                              screen=screen)
        self.assertEqual(payload["collection"], "incomplete")
        self.assertTrue(any("advisory" in reason for reason in incomplete))


class WriteTests(RepoCase):
    def payload(self):
        return {"netwatch": 1, "generated": "2026-11-21T19:00:00Z", "collection": "complete",
                "findings": [{"type": "unpinned", "severity": "high", "ecosystem": "uv",
                              "evidence": "x", "action": "uv lock"}], "leads": []}

    def test_write_refuses_symlinked_netwatch_and_leaves_target_alone(self):
        zshrc = self.root / "zshrc"
        zshrc.write_text("untouched")
        (self.repo / ".netwatch").symlink_to(zshrc)
        with self.assertRaises(tickets.Refused):
            tickets.write(self.repo, tickets.render(self.payload()))
        self.assertEqual(zshrc.read_text(), "untouched")

    def test_write_refuses_a_directory_named_netwatch(self):
        (self.repo / ".netwatch").mkdir()
        with self.assertRaises(tickets.Refused):
            tickets.write(self.repo, tickets.render(self.payload()))

    def test_write_preserves_a_foreign_netwatch(self):
        (self.repo / ".netwatch").write_text("# my own notes\n")
        with self.assertRaises(tickets.Refused):
            tickets.write(self.repo, tickets.render(self.payload()))
        self.assertEqual((self.repo / ".netwatch").read_text(), "# my own notes\n")

    def test_write_replaces_a_netwatch_ticket_and_leaves_no_temp(self):
        tickets.write(self.repo, tickets.render(self.payload()))
        tickets.write(self.repo, tickets.render(self.payload()))
        body = (self.repo / ".netwatch").read_text()
        self.assertTrue(body.startswith(HEADER))
        self.assertEqual([p.name for p in self.repo.iterdir() if p.name.startswith(".netwatch.tmp-")], [])

    def test_stale_temp_is_cleaned_and_fresh_one_is_not(self):
        old = self.repo / (".netwatch.tmp-" + "a" * 32)
        old.write_text("")
        os.utime(old, (time.time() - 7200,) * 2)
        fresh = self.repo / (".netwatch.tmp-" + "b" * 32)
        fresh.write_text("")
        tickets.write(self.repo, tickets.render(self.payload()))
        self.assertFalse(old.exists())
        self.assertTrue(fresh.exists())

    def test_render_starts_with_the_header_and_carries_a_json_block(self):
        text = tickets.render(self.payload())
        self.assertTrue(text.startswith(HEADER))
        self.assertIn("```json", text)
        self.assertIn('"findings"', text)


class GitFlagTests(RepoCase):
    def test_git_reads_carry_no_side_effect_flags(self):
        calls = []
        tickets.git(self.repo, "status", "--porcelain", runner=lambda argv, **kw: calls.append(argv) or "")
        argv = calls[0]
        self.assertEqual(argv[:2], ["git", "--no-optional-locks"])
        self.assertIn("-C", argv)
        for flag in ("--no-optional-locks", "core.fsmonitor=", "core.untrackedCache="):
            self.assertIn(flag, argv)
        self.assertEqual(os.environ.get("GIT_OPTIONAL_LOCKS"), None)

    def test_git_log_disables_commit_signature_verification(self):
        calls = []
        tickets.git(self.repo, "log", "-1", "--format=%H", runner=lambda argv, **kw: calls.append(argv) or "")
        self.assertIn("log.showSignature=false", calls[0])
        self.assertLess(calls[0].index("log.showSignature=false"), calls[0].index("log"))
        self.assertIn("--no-show-signature", calls[0])
        self.assertLess(calls[0].index("log"), calls[0].index("--no-show-signature"))

    def test_git_env_sets_optional_locks_off(self):
        seen = {}
        tickets.git(self.repo, "status", "--porcelain",
                    runner=lambda argv, **kw: seen.update(kw) or "")
        self.assertEqual(seen["env"]["GIT_OPTIONAL_LOCKS"], "0")


class WriteDecisionTests(RepoCase):
    def test_nothing_collected_and_no_previous_ticket_writes_nothing(self):
        payload = {"netwatch": 1, "generated": "x", "collection": "incomplete",
                   "error": "both parsers failed", "findings": [], "leads": []}
        self.assertFalse(tickets.should_write(payload, self.repo))

    def test_nothing_collected_with_a_previous_ticket_leaves_it_untouched(self):
        tickets.write(self.repo, tickets.render({"netwatch": 1, "generated": "old",
                                                 "collection": "complete", "findings": [], "leads": []}))
        before = (self.repo / ".netwatch").read_text()
        payload = {"netwatch": 1, "generated": "x", "collection": "incomplete",
                   "error": "both parsers failed", "findings": [], "leads": []}
        self.assertFalse(tickets.should_write(payload, self.repo))
        self.assertEqual((self.repo / ".netwatch").read_text(), before)

    def test_partial_collection_writes_a_ticket_marked_incomplete(self):
        payload = {"netwatch": 1, "generated": "x", "collection": "incomplete",
                   "error": "package-lock.json unreadable",
                   "findings": [{"type": "unpinned", "severity": "high", "ecosystem": "uv",
                                 "evidence": "x", "action": "uv lock"}], "leads": []}
        self.assertTrue(tickets.should_write(payload, self.repo))


